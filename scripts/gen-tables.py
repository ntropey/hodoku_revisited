#!/usr/bin/env python3
"""Generate packages/core/src/generated/*.ts from the original HoDoKu 2.2.0 sources.

Usage: python3 scripts/gen-tables.py <path-to>/HoDoKu/tags/release2.2.0 

Generating the big constant tables (solution types, default solver steps)
avoids transcription errors when porting.
"""
import re, sys, os, json

root = sys.argv[1]
src = os.path.join(root, "src")
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "packages", "core", "src", "generated")
os.makedirs(out, exist_ok=True)

def read(p):
    return open(os.path.join(src, p), encoding="utf-8", errors="replace").read()

def props(p):
    d = {}
    for line in read(p).splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        k, _, v = line.partition("=")
        k = re.sub(r"\\(.)", r"\1", k.strip())
        v = re.sub(r"\\u([0-9a-fA-F]{4})", lambda m: chr(int(m.group(1), 16)), v.strip())
        d[k] = v
    return d

HEADER = """// GENERATED by scripts/gen-tables.py from HoDoKu 2.2.0 -- do not edit by hand.
// Copyright (C) 2008-12 Bernhard Hobiger (original data); GPL-3.0-or-later.
"""

# ---- SolutionType
names = props("intl/SolutionType.properties")
st = read("sudoku/SolutionType.java")
rows = re.findall(r'^\s*([A-Z_0-9]+)\(java\.util\.ResourceBundle\.getBundle\("intl/SolutionType"\)\.getString\("([^"]+)"\),\s*"([^"]*)",\s*"([^"]*)"\)', st, re.M)
assert len(rows) > 100, len(rows)
ts = HEADER + "\nexport const SOLUTION_TYPE_NAMES = [\n" + "".join(f"  '{r[0]}',\n" for r in rows) + "] as const;\n\n"
ts += "export type SolutionType = (typeof SOLUTION_TYPE_NAMES)[number];\n\n"
ts += "export interface SolutionTypeInfo {\n  stepName: string;\n  libraryType: string;\n  argName: string;\n}\n\n"
ts += "export const SOLUTION_TYPE_INFO: Record<SolutionType, SolutionTypeInfo> = {\n"
for n, key, lib, arg in rows:
    ts += f"  {n}: {{ stepName: {json.dumps(names[key], ensure_ascii=False)}, libraryType: '{lib}', argName: '{arg}' }},\n"
ts += "};\n"
open(os.path.join(out, "solutionType.ts"), "w", encoding="utf-8").write(ts)

# ---- Default solver steps and difficulty levels
opt = read("sudoku/Options.java")
steps = re.findall(r"^\s*new StepConfig\(([\w.]+(?: - 1)?), SolutionType\.(\w+), DifficultyType\.(\w+)\.ordinal\(\), SolutionCategory\.(\w+), (\d+), (\d+), (true|false), (true|false), ([\w.]+(?: - 1)?), (true|false), (true|false)\)", opt, re.M)
assert len(steps) == 92, len(steps)
def num(s):
    return {"Integer.MAX_VALUE": "2147483647", "Integer.MAX_VALUE - 1": "2147483646"}.get(s, s)
ts = HEADER + "\nimport type { SolutionType } from './solutionType.js';\n\n"
ts += "export const DIFFICULTY_TYPES = ['INCOMPLETE', 'EASY', 'MEDIUM', 'HARD', 'UNFAIR', 'EXTREME'] as const;\n"
ts += "export type DifficultyType = (typeof DIFFICULTY_TYPES)[number];\n\n"
cats = re.findall(r'^\s*([A-Z_]+)\("', read("sudoku/SolutionCategory.java"), re.M)
ts += "export const SOLUTION_CATEGORIES = [" + ", ".join(f"'{c}'" for c in cats) + "] as const;\n"
ts += "export type SolutionCategory = (typeof SOLUTION_CATEGORIES)[number];\n\n"
lvblock = opt[opt.index("DEFAULT_DIFFICULTY_LEVELS"):opt.index("private DifficultyLevel[] difficultyLevels")]
lv = re.findall(r"new DifficultyLevel\(DifficultyType\.(\w+), (\w+(?:\.\w+)?),", lvblock)
assert len(lv) == 6, len(lv)
ts += "export const DEFAULT_DIFFICULTY_LEVELS: ReadonlyArray<{ type: DifficultyType; ordinal: number; maxScore: number }> = [\n"
for i, (t, m) in enumerate(lv):
    ts += f"  {{ type: '{t}', ordinal: {i}, maxScore: {num(m)} }},\n"
ts += "];\n\n"
ts += """export interface StepConfig {
  index: number; // search order when solving
  type: SolutionType;
  level: number; // index into the difficulty levels
  category: SolutionCategory;
  baseScore: number;
  adminScore: number;
  enabled: boolean;
  allStepsEnabled: boolean;
  indexProgress: number;
  enabledProgress: boolean;
  enabledTraining: boolean;
}

/** Same order as DEFAULT_SOLVER_STEPS in the original Options.java (unsorted). */
export const DEFAULT_SOLVER_STEPS: ReadonlyArray<StepConfig> = [
"""
for (idx, typ, lvl, cat, base, adm, en, allen, idxp, enp, ent) in steps:
    ts += (f"  {{ index: {num(idx)}, type: '{typ}', level: {lvl and ['INCOMPLETE','EASY','MEDIUM','HARD','UNFAIR','EXTREME'].index(lvl)}, "
           f"category: '{cat}', baseScore: {base}, adminScore: {adm}, enabled: {en}, allStepsEnabled: {allen}, "
           f"indexProgress: {num(idxp)}, enabledProgress: {enp}, enabledTraining: {ent} }},\n")
ts += "];\n"
open(os.path.join(out, "defaultSteps.ts"), "w", encoding="utf-8").write(ts)
print("ok:", len(rows), "solution types,", len(steps), "step configs,", len(lv), "levels")
